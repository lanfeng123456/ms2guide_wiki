const dictionaries: Record<Exclude<Locale, "en">, Dictionary> = { de, fr, "pt-br": ptBr };

function translateValue<T>(value: T, dictionary: Dictionary): T {
  if (typeof value === "string") return (dictionary[value] ?? value) as T;
  if (Array.isArray(value)) return value.map((item) => translateValue(item, dictionary)) as T;
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translateValue(item, dictionary)])) as T;
  }
  return value;
}

export function getLocalizedHomeContent(locale: Locale): typeof homeContent {
  return locale === "en" ? homeContent : translateValue(homeContent, dictionaries[locale]);
}

export function localeFromPathname(pathname: string): Locale {
  const prefix = pathname.split("/").filter(Boolean)[0]?.toLowerCase();
  return locales.includes(prefix as Locale) ? (prefix as Locale) : "en";
}

export function localizedPath(pathname: string, target: Locale): string {
  const parts = pathname.split("/").filter(Boolean);
  if (locales.includes(parts[0] as Locale)) parts.shift();
  const suffix = parts.length ? `/${parts.join("/")}` : "";
  return target === "en" ? suffix || "/" : `/${target}${suffix}`;
}
